/*
  The series of the manga library of the 3D room, in the order they stand on
  the shelves, from the top left. The title is what shows beside the pointer.
  `volumes` only sets how long a series is on its shelf: the counts are from
  memory, rounded for the long ones, and are shown nowhere. A series may name
  the colours of its spines (the spine, the mark that stands for its title,
  a band at its foot) and the picture its spines form side by side; the
  others get colours of their own from their title.

  The pictures are drawn for this room: none of them copies the artwork of a
  publisher.
*/
import type { Swatch } from '../room/voxel/palette.ts';

export type Mural = 'dragon' | 'sea' | 'fox' | 'moon' | 'circle' | 'wall' | 'court' | 'sword' | 'brush' | 'net' | 'apple' | 'checker' | 'stars' | 'rainbow';

